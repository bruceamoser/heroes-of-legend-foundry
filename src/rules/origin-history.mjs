export function originPair(origin, selection) {
  if (
    !origin ||
    selection?.id !== origin.id ||
    !Number.isInteger(selection?.pair)
  )
    return null;
  if (selection.retainedFrom !== undefined) {
    if (selection.retainedFrom !== ORIGIN_HISTORY_SOURCE) return null;
    return ORIGIN_HISTORY[origin.id]?.pairs?.[selection.pair] ?? null;
  }
  return origin.pairs?.[selection.pair] ?? null;
}

/** A retained selection is shown beside today's choices, never offered to a new hero. */
export function originPairOptions(origin, selection) {
  const rows = origin.pairs.map((pair, index) => ({
    ...pair,
    value: `${origin.id}|${index}`,
    selected:
      selection?.id === origin.id &&
      selection?.pair === index &&
      !selection.retainedFrom,
    retained: false,
  }));
  if (selection?.retainedFrom && selection.id === origin.id) {
    const pair = originPair(origin, selection);
    if (pair)
      rows.unshift({
        ...pair,
        value: `${origin.id}|${selection.pair}|${selection.retainedFrom}`,
        selected: true,
        retained: true,
      });
  }
  return rows;
}
